package com.example.ui.screens

import androidx.compose.animation.AnimatedVisibility
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.itemsIndexed
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.data.model.HealthOption
import com.example.data.model.HealthQuestion
import com.example.ui.components.GlassCard
import com.example.ui.theme.*

@Composable
fun HealthCheckScreen(
    questions: List<HealthQuestion>
) {
    // Map of question id to selected option index
    var selectedAnswers by remember { mutableStateOf(mapOf<String, Int>()) }
    var reportGenerated by remember { mutableStateOf(false) }

    val allAnswered = selectedAnswers.size == questions.size

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(CarbonBlack),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Header
        item {
            Column {
                Text(
                    text = "SYSTEM HEALTH ASSESSMENT",
                    color = TechCyan,
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    letterSpacing = 1.2.sp
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = "Motorcycle Health Check",
                    color = TitaniumSilver,
                    fontSize = 22.sp,
                    fontWeight = FontWeight.ExtraBold
                )
                Spacer(modifier = Modifier.height(6.dp))
                Text(
                    text = "Answer 8 system questions to generate an instant health rating and recommended next steps for your bike.",
                    color = MutedSlate,
                    fontSize = 13.sp
                )
            }
        }

        if (reportGenerated) {
            // GENERATED HEALTH REPORT
            item {
                val goodAnswersCount = selectedAnswers.count { (qId, optIdx) ->
                    val q = questions.firstOrNull { it.id == qId }
                    q?.options?.getOrNull(optIdx)?.isGood == true
                }
                val totalQuestions = questions.size
                val scorePercent = (goodAnswersCount.toFloat() / totalQuestions * 100).toInt()

                GlassCard(
                    modifier = Modifier.fillMaxWidth(),
                    borderColor = if (scorePercent >= 80) StatusGood else if (scorePercent >= 50) StatusDueSoon else StatusOverdue
                ) {
                    Column(
                        modifier = Modifier.padding(20.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Text(
                            text = "OFFICIAL MOTORCYCLE HEALTH REPORT",
                            color = RacingAmber,
                            fontWeight = FontWeight.Bold,
                            fontSize = 11.sp,
                            letterSpacing = 1.sp
                        )
                        Spacer(modifier = Modifier.height(10.dp))
                        Text(
                            text = "$scorePercent%",
                            color = if (scorePercent >= 80) StatusGood else if (scorePercent >= 50) StatusDueSoon else StatusOverdue,
                            fontSize = 44.sp,
                            fontWeight = FontWeight.ExtraBold
                        )
                        Text(
                            text = when {
                                scorePercent >= 80 -> "EXCELLENT CONDITION — Ready to Ride"
                                scorePercent >= 50 -> "ATTENTION REQUIRED — Address Yellow Items"
                                else -> "CRITICAL CHECKS NEEDED — Resolve Before Riding"
                            },
                            color = TitaniumSilver,
                            fontWeight = FontWeight.Bold,
                            fontSize = 13.sp
                        )

                        Spacer(modifier = Modifier.height(16.dp))
                        Button(
                            onClick = {
                                reportGenerated = false
                                selectedAnswers = emptyMap()
                            },
                            colors = ButtonDefaults.buttonColors(containerColor = GunmetalSurface),
                            border = androidx.compose.foundation.BorderStroke(1.dp, GunmetalBorder),
                            shape = RoundedCornerShape(8.dp)
                        ) {
                            Icon(imageVector = Icons.Default.Refresh, contentDescription = null, tint = TitaniumSilver)
                            Spacer(modifier = Modifier.width(6.dp))
                            Text("Retake Assessment", color = TitaniumSilver, fontSize = 12.sp)
                        }
                    }
                }
            }

            // System Breakdown
            item {
                Text(
                    text = "SYSTEM BY SYSTEM EVALUATION",
                    color = MutedSlate,
                    fontSize = 11.sp,
                    fontWeight = FontWeight.Bold,
                    letterSpacing = 1.sp
                )
            }

            itemsIndexed(questions) { _, q ->
                val chosenIdx = selectedAnswers[q.id] ?: 0
                val chosenOpt = q.options.getOrNull(chosenIdx)
                val isGood = chosenOpt?.isGood == true

                GlassCard(
                    modifier = Modifier.fillMaxWidth(),
                    borderColor = if (isGood) StatusGood.copy(alpha = 0.5f) else StatusOverdue.copy(alpha = 0.5f)
                ) {
                    Row(
                        modifier = Modifier.padding(14.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(
                                text = q.system.uppercase(),
                                color = TechCyan,
                                fontSize = 10.sp,
                                fontWeight = FontWeight.Bold,
                                letterSpacing = 1.sp
                            )
                            Text(
                                text = chosenOpt?.text.orEmpty(),
                                color = TitaniumSilver,
                                fontSize = 13.sp,
                                fontWeight = FontWeight.SemiBold
                            )
                            if (!chosenOpt?.note.isNullOrBlank()) {
                                Spacer(modifier = Modifier.height(2.dp))
                                Text(
                                    text = "Action: ${chosenOpt?.note}",
                                    color = if (isGood) StatusGood else StatusOverdue,
                                    fontSize = 11.sp
                                )
                            }
                        }

                        Surface(
                            shape = RoundedCornerShape(6.dp),
                            color = if (isGood) StatusGood.copy(alpha = 0.15f) else StatusOverdue.copy(alpha = 0.15f),
                            border = androidx.compose.foundation.BorderStroke(1.dp, if (isGood) StatusGood else StatusOverdue)
                        ) {
                            Text(
                                text = if (isGood) "GOOD" else "CHECK NEEDED",
                                color = if (isGood) StatusGood else StatusOverdue,
                                fontSize = 10.sp,
                                fontWeight = FontWeight.Bold,
                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 3.dp)
                            )
                        }
                    }
                }
            }

        } else {
            // QUESTIONNAIRE IN PROGRESS
            itemsIndexed(questions) { index, question ->
                GlassCard(
                    modifier = Modifier.fillMaxWidth(),
                    borderColor = GunmetalBorder
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Surface(
                                shape = RoundedCornerShape(6.dp),
                                color = RacingAmber.copy(alpha = 0.15f)
                            ) {
                                Text(
                                    text = "QUESTION ${index + 1} OF ${questions.size} • ${question.system.uppercase()}",
                                    color = RacingAmber,
                                    fontSize = 10.sp,
                                    fontWeight = FontWeight.Bold,
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                                )
                            }
                        }

                        Spacer(modifier = Modifier.height(8.dp))
                        Text(
                            text = question.questionText,
                            color = TitaniumSilver,
                            fontWeight = FontWeight.Bold,
                            fontSize = 14.sp
                        )

                        Spacer(modifier = Modifier.height(12.dp))

                        question.options.forEachIndexed { optIndex, option ->
                            val isSelected = selectedAnswers[question.id] == optIndex
                            Surface(
                                onClick = {
                                    selectedAnswers = selectedAnswers + (question.id to optIndex)
                                },
                                shape = RoundedCornerShape(8.dp),
                                color = if (isSelected) RacingAmber.copy(alpha = 0.15f) else CharcoalDark,
                                border = androidx.compose.foundation.BorderStroke(
                                    1.dp,
                                    if (isSelected) RacingAmber else GunmetalBorder
                                ),
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(vertical = 4.dp)
                            ) {
                                Row(
                                    modifier = Modifier.padding(12.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    RadioButton(
                                        selected = isSelected,
                                        onClick = {
                                            selectedAnswers = selectedAnswers + (question.id to optIndex)
                                        },
                                        colors = RadioButtonDefaults.colors(
                                            selectedColor = RacingAmber,
                                            unselectedColor = MutedSlate
                                        )
                                    )
                                    Spacer(modifier = Modifier.width(6.dp))
                                    Text(
                                        text = option.text,
                                        color = if (isSelected) TitaniumSilver else MutedSlate,
                                        fontSize = 12.sp,
                                        lineHeight = 16.sp
                                    )
                                }
                            }
                        }
                    }
                }
            }

            item {
                Button(
                    onClick = { reportGenerated = true },
                    enabled = allAnswered,
                    colors = ButtonDefaults.buttonColors(
                        containerColor = RacingAmber,
                        disabledContainerColor = GunmetalSurface
                    ),
                    shape = RoundedCornerShape(10.dp),
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(50.dp)
                ) {
                    Text(
                        text = if (allAnswered) "Generate Health Report" else "Answer All Questions (${selectedAnswers.size}/${questions.size})",
                        color = if (allAnswered) Color.Black else MutedSlate,
                        fontWeight = FontWeight.Bold,
                        fontSize = 14.sp
                    )
                }
            }
        }
    }
}
